function model = agentTypeModel(cfg, type)
%AGENTTYPEMODEL Return configured physical and behavioural limits for a type.
% Inputs: cfg, defaultConfig output; type, integer agent type in [1,10].
% Outputs: model with speed (m/s), accelerations (m/s^2), turn rate (rad/s),
% separation radius/spread (m), Boid weights, and hypothesis count.
% Example: model = agentTypeModel(defaultConfig(), 3);

validateattributes(type, {'numeric'}, ...
    {'scalar','real','finite','integer','>=',1, ...
     '<=',numel(cfg.world.maxSpeeds)}, mfilename, 'type');
model = struct( ...
    'maxSpeedMps', cfg.world.maxSpeeds(type), ...
    'maxAccelerationMps2', cfg.world.maxAccelerations(type), ...
    'maxDecelerationMps2', cfg.world.maxDecelerations(type), ...
    'maxLateralAccelerationMps2', ...
        cfg.prediction.maxLateralAccelerationsMps2(type), ...
    'maxTurnRateRadps', cfg.prediction.maxTurnRatesRadps(type), ...
    'separationRadiusM', cfg.prediction.separationRadiiM(type), ...
    'boidWeights', cfg.prediction.boidWeights(type, :), ...
    'lateralManoeuvreSpreadM', ...
        cfg.prediction.lateralManoeuvreSpreadM(type), ...
    'hypothesisCount', cfg.prediction.hypothesisCounts(type), ...
    'randomAccelerationStdMps2', ...
        cfg.prediction.randomAccelerationStdMps2(type), ...
    'sigmaGrowthMps', cfg.prediction.sigmaGrowthMps(type));
end
