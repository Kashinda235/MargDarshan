function riskField = computeRiskField(gridMap, predictionRiskMap, ego, cfg)
%COMPUTERISKFIELD Combine static and predicted collision risk over time.
% Inputs: gridMap, ego-centric [ny x nx] probabilities/costs;
% predictionRiskMap, [nx x ny x steps] predicted collision probabilities;
% ego, world-frame pose in m/rad; cfg, defaults including ego dimensions.
% Outputs: riskField with risk [ny x nx x steps], maxRisk [ny x nx],
% localX/localY cell-centre coordinates in m, and timestamp in s.
% The ego footprint plus cfg.pocket.safetyMarginM is conservatively
% inflated in the ego frame.
% Example: field = computeRiskField(map, predictedRisk, ego, cfg);

if nargin < 4 || isempty(cfg)
    cfg = defaultConfig();
end
expectedGridSize = [cfg.grid.ny cfg.grid.nx];
if ~isstruct(gridMap) || ~isfield(gridMap, 'occupancy') || ...
        ~isequal(size(gridMap.occupancy), expectedGridSize) || ...
        ~isfield(gridMap, 'traversability') || ...
        ~isequal(size(gridMap.traversability), expectedGridSize) || ...
        ~isfield(gridMap, 'surfaceCost') || ...
        ~isequal(size(gridMap.surfaceCost), expectedGridSize)
    error('computeRiskField:InvalidGridMap', ...
        'gridMap must contain correctly sized occupancy, traversability, and surfaceCost layers.');
end
mapLayers = {gridMap.occupancy, gridMap.traversability, ...
    gridMap.surfaceCost};
for layerIndex = 1:numel(mapLayers)
    layer = mapLayers{layerIndex};
    if ~isnumeric(layer) || ~isreal(layer) || ...
            any(~isfinite(layer(:))) || any(layer(:) < 0) || ...
            any(layer(:) > 1)
        error('computeRiskField:InvalidGridLayer', ...
            'Grid probability and cost layers must be real and in [0,1].');
    end
end
if isfield(gridMap, 'obstacleProb') && ...
        (~isequal(size(gridMap.obstacleProb), expectedGridSize) || ...
        ~isnumeric(gridMap.obstacleProb) || ...
        ~isreal(gridMap.obstacleProb) || ...
        any(~isfinite(gridMap.obstacleProb(:))) || ...
        any(gridMap.obstacleProb(:) < 0) || ...
        any(gridMap.obstacleProb(:) > 1))
    error('computeRiskField:InvalidObstacleProbability', ...
        'gridMap.obstacleProb must be a grid-sized probability layer in [0,1].');
end
if ~isnumeric(predictionRiskMap) || ...
        ~isreal(predictionRiskMap) || ...
        size(predictionRiskMap, 1) ~= cfg.grid.nx || ...
        size(predictionRiskMap, 2) ~= cfg.grid.ny || ...
        size(predictionRiskMap, 3) ~= cfg.prediction.steps || ...
        any(~isfinite(predictionRiskMap(:))) || ...
        any(predictionRiskMap(:) < 0) || ...
        any(predictionRiskMap(:) > 1)
    error('computeRiskField:InvalidPredictionRiskMap', ...
        'predictionRiskMap must be [nx x ny x steps] probabilities in [0,1].');
end

occupancy = max(gridMap.occupancy, zeros(expectedGridSize));
if isfield(gridMap, 'obstacleProb') && ...
        isequal(size(gridMap.obstacleProb), expectedGridSize)
    occupancy = max(occupancy, gridMap.obstacleProb);
end
priorOccupancy = 1.0/(1.0 + ...
    exp(-cfg.perception.occupancyPriorLogOdds));
occupancyRisk = min(1.0, max(0.0, ...
    (occupancy-priorOccupancy)/(1.0-priorOccupancy)));
traversabilityBaseline = 1.0-priorOccupancy;
nonTraversabilityRisk = min(1.0, max(0.0, ...
    (traversabilityBaseline-gridMap.traversability) ...
    / traversabilityBaseline));
surfaceRisk = min(1.0, max(0.0, gridMap.surfaceCost));
staticRisk = 1.0-(1.0-occupancyRisk) ...
    .*(1.0-nonTraversabilityRisk).*(1.0-surfaceRisk);

inflateX = ceil((cfg.vehicle.length/2 ...
    + cfg.pocket.safetyMarginM)/cfg.grid.resolution);
inflateY = ceil((cfg.vehicle.width/2 ...
    + cfg.pocket.safetyMarginM)/cfg.grid.resolution);
staticRisk = inflateRisk(staticRisk, inflateY, inflateX);
timeCount = cfg.prediction.steps;
dynamicRisk = permute(predictionRiskMap, [2 1 3]);
dynamicRisk = inflateRisk(dynamicRisk, inflateY, inflateX);
risk = 1.0-(1.0-staticRisk).*(1.0-dynamicRisk);

if isfield(gridMap, 'originX')
    originX = gridMap.originX;
else
    originX = -((cfg.grid.nx-1)/2)*cfg.grid.resolution;
end
if isfield(gridMap, 'originY')
    originY = gridMap.originY;
else
    originY = -((cfg.grid.ny-1)/2)*cfg.grid.resolution;
end
if ~isnumeric(originX) || ~isscalar(originX) || ~isfinite(originX) || ...
        ~isnumeric(originY) || ~isscalar(originY) || ~isfinite(originY)
    error('computeRiskField:InvalidGridOrigin', ...
        'Grid origins must be finite scalar coordinates in m.');
end
localX = originX+(0:cfg.grid.nx-1)*cfg.grid.resolution;
localY = (originY+(0:cfg.grid.ny-1)*cfg.grid.resolution)';
timestamp = 0.0;
if isfield(gridMap, 'timestamp')
    timestamp = gridMap.timestamp;
end
riskField = struct( ...
    'risk', risk, ...
    'maxRisk', max(risk, [], 3), ...
    'localX', localX, ...
    'localY', localY, ...
    'timestamp', timestamp);
end

function inflated = inflateRisk(risk, radiusY, radiusX)
inflated = movmax(risk, [radiusY radiusY], 1);
inflated = movmax(inflated, [radiusX radiusX], 2);
end
