function ax = plotPocket(scenario, agents, ego, pocketState, riskField, ax, cfg)
%PLOTPOCKET Overlay the pocket and time-horizon risk on a world snapshot.
% Inputs: scenario and agents, world-frame scene; ego, world pose in m/rad;
% pocketState, safe-pocket contract; riskField from computeRiskField; ax,
% optional axes; cfg, defaults. Outputs: axes handle.
% Example: plotPocket(s, agents, ego, pocket, field, [], defaultConfig());

if nargin < 6 || isempty(ax)
    ax = gca;
end
if nargin < 7 || isempty(cfg)
    cfg = defaultConfig();
end
if ~isstruct(riskField) || ~isfield(riskField, 'risk') || ...
        size(riskField.risk, 1) ~= cfg.grid.ny || ...
        size(riskField.risk, 2) ~= cfg.grid.nx || ...
        size(riskField.risk, 3) ~= cfg.prediction.steps || ...
        ~isfield(riskField, 'localX') || ...
        ~isfield(riskField, 'localY') || ...
        numel(riskField.localX) ~= cfg.grid.nx || ...
        numel(riskField.localY) ~= cfg.grid.ny
    error('plotPocket:InvalidRiskField', ...
        'riskField must contain the configured [ny x nx x steps] risk array.');
end
plotWorld(scenario, agents, ego, ax, cfg);
hold(ax, 'on');
localMaximumRisk = max(riskField.risk, [], 3);
[localGridX, localGridY] = meshgrid( ...
    riskField.localX, riskField.localY);
worldGridX = ego.x+cos(ego.yaw)*localGridX-sin(ego.yaw)*localGridY;
worldGridY = ego.y+sin(ego.yaw)*localGridX+cos(ego.yaw)*localGridY;
surface(ax, worldGridX, worldGridY, ...
    cfg.grid.resolution*ones(size(worldGridX)), localMaximumRisk, ...
    'FaceColor', 'texturemap', 'EdgeColor', 'none', 'FaceAlpha', 0.45, ...
    'HandleVisibility', 'off');
if ~pocketState.isEmpty && pocketState.boundaryCount > 0
    localBoundary = pocketState.boundary( ...
        1:pocketState.boundaryCount, :);
    worldBoundaryX = ego.x+cos(ego.yaw)*localBoundary(:,1) ...
        -sin(ego.yaw)*localBoundary(:,2);
    worldBoundaryY = ego.y+sin(ego.yaw)*localBoundary(:,1) ...
        +cos(ego.yaw)*localBoundary(:,2);
    patch(ax, worldBoundaryX, worldBoundaryY, [0.1 0.85 0.25], ...
        'FaceAlpha', 0.12, 'EdgeColor', [0.0 0.55 0.1], ...
        'LineWidth', 2.0, 'DisplayName', 'Safe pocket');
end
colormap(ax, parula);
colorbar(ax);
title(ax, sprintf('%s | t = %.1f s | pocket quality %.2f', ...
    scenario.name, scenario.time, pocketState.quality), ...
    'Interpreter', 'none');
hold(ax, 'off');
end
