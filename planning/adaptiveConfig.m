function decision = adaptiveConfig(riskSummary, previousDecision, cfg)
%ADAPTIVECONFIG Select a speed/horizon policy with mode hysteresis.
% Inputs: riskSummary with agentDensity (agents/m^2), minTTC (s),
% pocketArea (m^2), pocketDepth (m), and meanPredictionUncertainty (m);
% previousDecision with prior mode (optional); cfg, defaultConfig output.
% Outputs: fixed decision subset with targetSpeed (m/s), safetyMargin (m),
% horizon/replanPeriod (s), and mode (1 cruise, 2 cautious, 3 emergency).
% Example: d = adaptiveConfig(summary, types.decision(cfg), cfg);

if nargin < 3 || isempty(cfg)
    cfg = defaultConfig();
end
if nargin < 2 || isempty(previousDecision)
    previousDecision = types.decision(cfg);
end
requiredFields = {'agentDensity','minTTC','pocketArea','pocketDepth', ...
    'meanPredictionUncertainty'};
if ~isstruct(riskSummary) || ~all(isfield(riskSummary, requiredFields))
    error('adaptiveConfig:InvalidRiskSummary', ...
        'riskSummary must contain agentDensity, minTTC, pocketArea, pocketDepth, and meanPredictionUncertainty.');
end
for k = 1:numel(requiredFields)
    value = riskSummary.(requiredFields{k});
    if ~isnumeric(value) || ~isreal(value) || ~isscalar(value) || ...
            isnan(value) || value < 0 || ...
            (k ~= 2 && ~isfinite(value))
        error('adaptiveConfig:InvalidRiskSummary', ...
            'Risk summary values must be nonnegative real scalars; minTTC may be Inf.');
    end
end
if ~isstruct(previousDecision) || ~isfield(previousDecision, 'mode')
    error('adaptiveConfig:InvalidPreviousDecision', ...
        'previousDecision must contain a mode field.');
end
if ~isnumeric(previousDecision.mode) || ...
        ~isscalar(previousDecision.mode) || ...
        ~any(previousDecision.mode == [cfg.decisionModes.cruise, ...
        cfg.decisionModes.cautious, cfg.decisionModes.emergency])
    error('adaptiveConfig:InvalidPreviousDecision', ...
        'previousDecision.mode must be a configured decision mode.');
end

emergency = riskSummary.minTTC <= cfg.adaptive.emergencyTtcS || ...
    riskSummary.agentDensity >= cfg.adaptive.emergencyDensityPerM2 || ...
    riskSummary.pocketArea <= cfg.adaptive.emergencyPocketAreaM2 || ...
    riskSummary.pocketDepth <= cfg.adaptive.emergencyPocketDepthM || ...
    riskSummary.meanPredictionUncertainty >= ...
        cfg.adaptive.emergencyUncertaintyM;
cautious = riskSummary.minTTC <= cfg.adaptive.cautiousTtcS || ...
    riskSummary.agentDensity >= cfg.adaptive.cautiousDensityPerM2 || ...
    riskSummary.pocketArea <= cfg.adaptive.cautiousPocketAreaM2 || ...
    riskSummary.pocketDepth <= cfg.adaptive.cautiousPocketDepthM || ...
    riskSummary.meanPredictionUncertainty >= ...
        cfg.adaptive.cautiousUncertaintyM;

mode = cfg.decisionModes.cruise;
if emergency
    mode = cfg.decisionModes.emergency;
elseif cautious
    mode = cfg.decisionModes.cautious;
end
if previousDecision.mode == cfg.decisionModes.emergency && ...
        ~canReleaseEmergency(riskSummary, cfg)
    mode = cfg.decisionModes.emergency;
elseif previousDecision.mode == cfg.decisionModes.cautious && ...
        mode == cfg.decisionModes.cruise && ...
        ~canReleaseCautious(riskSummary, cfg)
    mode = cfg.decisionModes.cautious;
end

switch mode
    case cfg.decisionModes.cruise
        targetSpeed = min(cfg.adaptive.cruiseTargetSpeedMps, ...
            cfg.nav.localSpeedLimit);
        safetyMargin = cfg.pocket.safetyMarginM;
        horizon = cfg.adaptive.cruiseHorizonS;
        replanPeriod = cfg.adaptive.cruiseReplanPeriodS;
    case cfg.decisionModes.cautious
        targetSpeed = min(cfg.adaptive.cruiseTargetSpeedMps, ...
            cfg.nav.localSpeedLimit)*cfg.adaptive.cautiousSpeedFraction;
        safetyMargin = cfg.pocket.safetyMarginM* ...
            cfg.adaptive.cautiousSafetyMarginScale;
        horizon = cfg.adaptive.cautiousHorizonS;
        replanPeriod = cfg.adaptive.cautiousReplanPeriodS;
    otherwise
        targetSpeed = 0.0;
        safetyMargin = cfg.adaptive.emergencySafetyMarginM;
        horizon = cfg.adaptive.emergencyHorizonS;
        replanPeriod = cfg.simulation.dt;
end
decision = struct( ...
    'targetSpeed', targetSpeed, ...
    'safetyMargin', safetyMargin, ...
    'horizon', horizon, ...
    'replanPeriod', replanPeriod, ...
    'mode', mode);
end

function released = canReleaseEmergency(summary, cfg)
released = summary.minTTC > cfg.adaptive.emergencyReleaseTtcS && ...
    summary.agentDensity < cfg.adaptive.emergencyReleaseDensityPerM2 && ...
    summary.pocketArea > cfg.adaptive.emergencyReleasePocketAreaM2 && ...
    summary.pocketDepth > cfg.adaptive.emergencyReleasePocketDepthM && ...
    summary.meanPredictionUncertainty < ...
        cfg.adaptive.emergencyReleaseUncertaintyM;
end

function released = canReleaseCautious(summary, cfg)
released = summary.minTTC > cfg.adaptive.cautiousReleaseTtcS && ...
    summary.agentDensity < cfg.adaptive.cautiousReleaseDensityPerM2 && ...
    summary.pocketArea > cfg.adaptive.cautiousReleasePocketAreaM2 && ...
    summary.pocketDepth > cfg.adaptive.cautiousReleasePocketDepthM && ...
    summary.meanPredictionUncertainty < ...
        cfg.adaptive.cautiousReleaseUncertaintyM;
end
