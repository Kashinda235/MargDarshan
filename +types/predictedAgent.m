function prediction = predictedAgent(cfg)
%PREDICTEDAGENT Create an initialised predicted-agent contract.
% Inputs: cfg, defaultConfig output.
% Outputs: fixed-size prediction with cfg.prediction.steps samples and
% cfg.prediction.modes hypotheses; positions and sigma are in m, time in s,
% dimensions in m, and mode probabilities sum to one over active modes.
% Example: prediction = types.predictedAgent(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
steps = cfg.prediction.steps;
prediction = struct( ...
    'id', 0, ...
    'type', cfg.agentTypes.car, ...
    'length', 0.0, ...
    'width', 0.0, ...
    'confidence', 0.0, ...
    'T', steps, ...
    't', zeros(steps, 1), ...
    'x', zeros(steps, 1), ...
    'y', zeros(steps, 1), ...
    'sigma', zeros(steps, 1), ...
    'hypothesisCount', 0, ...
    'hypothesisX', zeros(steps, cfg.prediction.modes), ...
    'hypothesisY', zeros(steps, cfg.prediction.modes), ...
    'hypothesisYaw', zeros(steps, cfg.prediction.modes), ...
    'hypothesisSigma', zeros(steps, cfg.prediction.modes), ...
    'modeProbability', zeros(1, cfg.prediction.modes));
end
