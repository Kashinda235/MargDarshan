function prediction = predictedAgent(cfg)
%PREDICTEDAGENT Create an initialised predicted-agent contract.
% Inputs: cfg, defaultConfig output.
% Outputs: prediction with cfg.prediction.steps time samples, positions in m,
% uncertainty in m, and cfg.prediction.modes probabilities in [0,1].
% Example: prediction = types.predictedAgent(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
steps = cfg.prediction.steps;
prediction = struct( ...
    'id', 0, ...
    'T', steps, ...
    't', zeros(steps, 1), ...
    'x', zeros(steps, 1), ...
    'y', zeros(steps, 1), ...
    'sigma', zeros(steps, 1), ...
    'modeProbability', zeros(1, cfg.prediction.modes));
end
