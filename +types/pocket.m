function pocketState = pocket(cfg)
%POCKET Create an initialised traversable-pocket contract.
% Inputs: cfg, defaultConfig output.
% Outputs: pocketState with grid-sized logical mask, fixed-size [x y]
% boundary (m), boundaryCount, area (m^2), clearances/depth (m), quality
% [0,1], and empty/small flags.
% Example: pocketState = types.pocket(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
pocketState = struct( ...
    'mask', false(cfg.grid.ny, cfg.grid.nx), ...
    'boundary', zeros(cfg.planner.maxBoundaryVertices, 2), ...
    'boundaryCount', 0, ...
    'area', 0.0, ...
    'forwardDepth', 0.0, ...
    'lateralLeft', 0.0, ...
    'lateralRight', 0.0, ...
    'riskThreshold', cfg.riskThreshold, ...
    'quality', 0.0, ...
    'isEmpty', true, ...
    'isSmall', true);
end
