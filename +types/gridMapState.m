function state = gridMapState(cfg)
%GRIDMAPSTATE Create fixed-size temporal state for buildGridMap.
% Inputs: cfg, defaultConfig output.
% Outputs: state, ego-frame log odds in unitless log-odds and pose in m/rad.
% Example: state = types.gridMapState(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
state = struct( ...
    'initialized', false, ...
    'staticLogOdds', zeros(cfg.grid.ny, cfg.grid.nx), ...
    'dynamicLogOdds', zeros(cfg.grid.ny, cfg.grid.nx), ...
    'egoX', 0.0, ...
    'egoY', 0.0, ...
    'egoYaw', 0.0, ...
    'originX', 0.0, ...
    'originY', 0.0, ...
    'randomState', cfg.perception.randomSeed);
end
