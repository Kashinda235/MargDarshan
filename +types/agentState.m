function agent = agentState(cfg)
%AGENTSTATE Create an initialised agent-state contract.
% Inputs: cfg, defaultConfig output (optional).
% Outputs: agent with position (m), velocity (m/s), acceleration (m/s^2),
% yaw (rad), dimensions (m), confidence (0-1), and logical validity.
% Example: agent = types.agentState(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
agent = struct( ...
    'id', 0, ...
    'type', cfg.agentTypes.car, ...
    'x', 0.0, ...
    'y', 0.0, ...
    'vx', 0.0, ...
    'vy', 0.0, ...
    'ax', 0.0, ...
    'ay', 0.0, ...
    'yaw', 0.0, ...
    'length', 0.0, ...
    'width', 0.0, ...
    'confidence', 0.0, ...
    'valid', false);
end
