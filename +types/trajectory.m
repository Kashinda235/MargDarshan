function path = trajectory(cfg)
%TRAJECTORY Create an initialised trajectory contract.
% Inputs: cfg, defaultConfig output.
% Outputs: path with cfg.planner.samples samples; time in s, position in m,
% yaw in rad, speed in m/s, curvature in 1/m, and fixed cost fields.
% Example: path = types.trajectory(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
samples = cfg.planner.samples;
path = struct( ...
    't', zeros(samples, 1), ...
    'x', zeros(samples, 1), ...
    'y', zeros(samples, 1), ...
    'yaw', zeros(samples, 1), ...
    'v', zeros(samples, 1), ...
    'kappa', zeros(samples, 1), ...
    'cost', 0.0, ...
    'lateralOffset', 0.0, ...
    'targetSpeed', 0.0, ...
    'timeToOffset', 0.0, ...
    'rejectionCode', 0, ...
    'costBreakdown', struct( ...
        'routeDeviation', 0.0, ...
        'curvatureChange', 0.0, ...
        'jerk', 0.0, ...
        'speedError', 0.0, ...
        'comfort', 0.0, ...
        'collisionRisk', 0.0, ...
        'maxCollisionRisk', 0.0, ...
        'trafficRisk', 0.0, ...
        'temporalConsistency', 0.0), ...
    'feasible', false);
end
