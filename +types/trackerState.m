function state = trackerState(cfg)
%TRACKERSTATE Create fixed-capacity state for trackAgents.
% Inputs: cfg, defaultConfig output.
% Outputs: state, fixed-capacity filter state; positions in m, velocities
% in m/s, accelerations in m/s^2, covariance in corresponding SI units.
% Example: state = types.trackerState(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
state = struct( ...
    'active', false(1, cfg.maxAgents), ...
    'confirmed', false(1, cfg.maxAgents), ...
    'id', zeros(1, cfg.maxAgents), ...
    'hits', zeros(1, cfg.maxAgents), ...
    'misses', zeros(1, cfg.maxAgents), ...
    'age', zeros(1, cfg.maxAgents), ...
    'x', zeros(4, cfg.maxAgents), ...
    'covariance', zeros(4, 4, cfg.maxAgents), ...
    'acceleration', zeros(2, cfg.maxAgents), ...
    'length', zeros(1, cfg.maxAgents), ...
    'width', zeros(1, cfg.maxAgents), ...
    'yaw', zeros(1, cfg.maxAgents), ...
    'type', repmat(cfg.agentTypes.car, 1, cfg.maxAgents), ...
    'confidence', zeros(1, cfg.maxAgents), ...
    'isStatic', false(1, cfg.maxAgents), ...
    'nextId', 1);
end
