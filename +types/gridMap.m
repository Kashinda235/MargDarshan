function map = gridMap(cfg)
%GRIDMAP Create an initialised ego-centric grid-map contract.
% Inputs: cfg, defaultConfig output.
% Outputs: map with [ny x nx] layers; resolution in m/cell, origin in m,
% occupancy/probability layers in [0,1], height in m, timestamp in s.
% Example: map = types.gridMap(defaultConfig());

if nargin < 1
    cfg = defaultConfig();
end
layer = zeros(cfg.grid.ny, cfg.grid.nx);
map = struct( ...
    'resolution', cfg.grid.resolution, ...
    'originX', -((cfg.grid.nx-1)/2)*cfg.grid.resolution, ...
    'originY', -((cfg.grid.ny-1)/2)*cfg.grid.resolution, ...
    'nx', cfg.grid.nx, ...
    'ny', cfg.grid.ny, ...
    'occupancy', layer, ...
    'height', layer, ...
    'obstacleProb', layer, ...
    'traversability', layer, ...
    'surfaceCost', layer, ...
    'timestamp', 0.0);
end
