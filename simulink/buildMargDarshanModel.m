%BUILDMARGDARSHANMODEL Reproducibly create the MargDarshan Simulink model.
% Run from any folder after adding the repository to the MATLAB path.

cfg = initModel(defaultConfig());
modelName = 'MargDarshan';
modelFile = fullfile(fileparts(mfilename('fullpath')), 'MargDarshan.slx');

if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
shadowingWarning = warning( ...
    'query', 'Simulink:Engine:MdlFileShadowing');
warning('off', 'Simulink:Engine:MdlFileShadowing');
warningCleanup = onCleanup(@() warning( ...
    shadowingWarning.state, 'Simulink:Engine:MdlFileShadowing')); %#ok<NASGU>
new_system(modelName);
clear warningCleanup
set_param(modelName, ...
    'InitFcn', 'initModel;', ...
    'SolverType', 'Fixed-step', ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', 'cfg.simDt', ...
    'StartTime', '0', ...
    'StopTime', 'cfg.simulation.duration', ...
    'SignalLogging', 'on', ...
    'SignalLoggingName', 'logsout', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'SaveOutput', 'off');

subsystemNames = { ...
    'Scenario_World', 'Perception', 'Prediction', 'Planning', ...
    'Control', 'Vehicle', 'Logging_Scopes'};
subsystemLabels = { ...
    'Scenario/World', 'Perception', 'Prediction', 'Planning', ...
    'Control', 'Vehicle', 'Logging/Scopes'};
left = 40;
blockWidth = 140;
blockHeight = 75;
spacing = 70;

for k = 1:numel(subsystemNames)
    blockPath = [modelName '/' subsystemNames{k}];
    x = left+(k-1)*(blockWidth+spacing);
    add_block('simulink/Ports & Subsystems/Subsystem', blockPath, ...
        'Position', [x 120 x+blockWidth 120+blockHeight], ...
        'AttributesFormatString', subsystemLabels{k});
end

buildWorldSubsystem([modelName '/Scenario_World']);
buildPassthroughSubsystem([modelName '/Perception']);
buildPassthroughSubsystem([modelName '/Prediction']);
buildPlanningSubsystem([modelName '/Planning'], cfg);
buildPassthroughSubsystem([modelName '/Control']);
buildPassthroughSubsystem([modelName '/Vehicle']);
buildLoggingSubsystem([modelName '/Logging_Scopes']);

for k = 1:numel(subsystemNames)-1
    add_line(modelName, ...
        [subsystemNames{k} '/1'], [subsystemNames{k+1} '/1'], ...
        'autorouting', 'on');
end

set_param(modelName, 'SimulationCommand', 'update');
save_system(modelName, modelFile);

function buildWorldSubsystem(path)
%BUILDWORLDSUBSYSTEM Add the pipeline runner and its typed bus output.
% Inputs: path, Scenario/World subsystem path.
% Outputs: none; the subsystem emits a fixed-size pipeline bus.
% Example: buildWorldSubsystem('MargDarshan/Scenario_World');
deleteDefaultPorts(path);
add_block('simulink/User-Defined Functions/MATLAB System', ...
    [path '/PipelineRunner'], ...
    'System', 'MargDarshanRunner', ...
    'SimulateUsing', 'Interpreted execution', ...
    'Config', 'cfg', ...
    'ScenarioName', 'village', ...
    'Seed', '1', ...
    'DurationS', 'cfg.simulation.duration', ...
    'Planner', 'margdarshan', ...
    'MeasureTiming', 'false', ...
    'Position', [75 55 245 105]);
add_block('simulink/Ports & Subsystems/Out1', [path '/Frame'], ...
    'OutDataTypeStr', 'Bus: MargDarshanPipelineBus', ...
    'Position', [325 65 355 95]);
add_line(path, 'PipelineRunner/1', 'Frame/1', 'autorouting', 'on');
end

function buildPassthroughSubsystem(path)
%BUILDPASSTHROUGHSUBSYSTEM Add fixed-size bus input and output ports.
% Inputs: path, subsystem path.
% Outputs: none; the subsystem forwards the pipeline bus unchanged.
% Example: buildPassthroughSubsystem('MargDarshan/Perception');
deleteDefaultPorts(path);
addContractPorts(path);
add_line(path, 'FrameIn/1', 'FrameOut/1', 'autorouting', 'on');
end

function buildPlanningSubsystem(path, cfg)
%BUILDPLANNINGSUBSYSTEM Add the bus path and slower planner-rate transition.
% Inputs: path, Planning subsystem path; cfg, defaultConfig output.
% Outputs: none; mode is transitioned at cfg.simulink.plannerSampleTimeS.
% Example: buildPlanningSubsystem('MargDarshan/Planning',defaultConfig());
buildPassthroughSubsystem(path);
selector = [path '/DecisionMode'];
transition = [path '/PlannerRateTransition'];
terminator = [path '/RateTransitionSink'];
add_block('simulink/Signal Routing/Bus Selector', selector, ...
    'OutputSignals', 'mode', ...
    'Position', [80 130 170 160]);
add_block('simulink/Signal Attributes/Rate Transition', transition, ...
    'OutPortSampleTimeOpt', 'Specify', ...
    'OutPortSampleTime', 'cfg.simulink.plannerSampleTimeS', ...
    'Position', [215 130 275 160]);
add_block('simulink/Sinks/Terminator', terminator, ...
    'Position', [330 135 350 155]);
add_line(path, 'FrameIn/1', 'DecisionMode/1', 'autorouting', 'on');
add_line(path, 'DecisionMode/1', 'PlannerRateTransition/1', ...
    'autorouting', 'on');
add_line(path, 'PlannerRateTransition/1', 'RateTransitionSink/1', ...
    'autorouting', 'on');
if cfg.simulink.plannerSampleTimeS <= cfg.simDt
    error('buildMargDarshanModel:PlannerRate', ...
        'Planner sample time must be slower than the control sample time.');
end
end

function buildLoggingSubsystem(path)
%BUILDLOGGINGSUBSYSTEM Add workspace and Data Inspector metric logging.
% Inputs: path, Logging/Scopes subsystem path.
% Outputs: none; records speed, clearance, TTC, mode, and cost.
% Example: buildLoggingSubsystem('MargDarshan/Logging_Scopes');
buildPassthroughSubsystem(path);
signals = { ...
    'speed', 'simSpeed'; ...
    'minClearance', 'simMinimumClearance'; ...
    'TTC', 'simTTC'; ...
    'mode', 'simMode'; ...
    'cost', 'simCost'};
for k = 1:size(signals, 1)
    selector = sprintf('%s/Select_%d', path, k);
    sink = sprintf('%s/ToWorkspace_%d', path, k);
    y = 125+(k-1)*55;
    signalName = signals{k, 1};
    variableName = signals{k, 2};
    add_block('simulink/Signal Routing/Bus Selector', selector, ...
        'OutputSignals', signalName, ...
        'Position', [80 y 190 y+28]);
    add_block('simulink/Sinks/To Workspace', sink, ...
        'VariableName', variableName, ...
        'SaveFormat', 'Timeseries', ...
        'Position', [285 y 390 y+28]);
    add_line(path, 'FrameIn/1', sprintf('Select_%d/1', k), ...
        'autorouting', 'on');
    signalLine = add_line(path, sprintf('Select_%d/1', k), ...
        sprintf('ToWorkspace_%d/1', k), 'autorouting', 'on');
    Simulink.sdi.markSignalForStreaming(signalLine, 'on');
end
end

function deleteDefaultPorts(path)
%DELETEDEFAULTPORTS Remove the default subsystem ports.
% Inputs: path, subsystem path. Outputs: none.
% Example: deleteDefaultPorts('MargDarshan/Perception');
delete_block([path '/In1']);
delete_block([path '/Out1']);
end

function addContractPorts(path)
%ADDCONTRACTPORTS Add pipeline-bus subsystem ports.
% Inputs: path, subsystem path. Outputs: none; port data use a Simulink.Bus.
% Example: addContractPorts('MargDarshan/Perception');
add_block('simulink/Ports & Subsystems/In1', [path '/FrameIn'], ...
    'OutDataTypeStr', 'Bus: MargDarshanPipelineBus', ...
    'Position', [30 65 60 95]);
add_block('simulink/Ports & Subsystems/Out1', [path '/FrameOut'], ...
    'OutDataTypeStr', 'Bus: MargDarshanPipelineBus', ...
    'Position', [365 65 395 95]);
end
