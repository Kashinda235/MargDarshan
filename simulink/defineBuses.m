function buses = defineBuses(cfg)
%DEFINEBUSES Generate fixed-size Simulink.Bus objects from +types contracts.
% Inputs: cfg, defaultConfig output; array dimensions use configured sizes.
% Outputs: buses, names of the contract and pipeline bus objects installed
% in the base workspace.
% Example: buses = defineBuses(defaultConfig());

if nargin < 1 || isempty(cfg)
    cfg = defaultConfig();
end

contracts = { ...
    'MargDarshanAgentStateBus', types.agentState(cfg); ...
    'MargDarshanAgentListBus', types.agentList(cfg); ...
    'MargDarshanDecisionBus', types.decision(cfg); ...
    'MargDarshanEgoStateBus', types.egoState(); ...
    'MargDarshanGridMapBus', types.gridMap(cfg); ...
    'MargDarshanGridMapStateBus', types.gridMapState(cfg); ...
    'MargDarshanPocketBus', types.pocket(cfg); ...
    'MargDarshanPredictedAgentBus', types.predictedAgent(cfg); ...
    'MargDarshanTrackerStateBus', types.trackerState(cfg); ...
    'MargDarshanTrajectoryBus', types.trajectory(cfg)};

for k = 1:size(contracts, 1)
    busName = contracts{k, 1};
    bus = makeBus(contracts{k, 2}, busName);
    assignin('base', busName, bus);
end

pipeline = struct( ...
    'ego', types.egoState(), ...
    'agents', types.agentList(cfg), ...
    'prediction', types.predictedAgent(cfg), ...
    'decision', types.decision(cfg), ...
    'pocket', types.pocket(cfg), ...
    'command', struct('accel', 0.0, 'steer', 0.0, 'brake', 0.0), ...
    'speed', 0.0, ...
    'minClearance', 0.0, ...
    'TTC', 0.0, ...
    'mode', 0.0, ...
    'cost', 0.0);
pipelineBus = makeBus(pipeline, 'MargDarshanPipelineBus');
assignin('base', 'MargDarshanPipelineBus', pipelineBus);

buses = struct( ...
    'agentState', 'MargDarshanAgentStateBus', ...
    'agentList', 'MargDarshanAgentListBus', ...
    'decision', 'MargDarshanDecisionBus', ...
    'egoState', 'MargDarshanEgoStateBus', ...
    'gridMap', 'MargDarshanGridMapBus', ...
    'gridMapState', 'MargDarshanGridMapStateBus', ...
    'pocket', 'MargDarshanPocketBus', ...
    'predictedAgent', 'MargDarshanPredictedAgentBus', ...
    'trackerState', 'MargDarshanTrackerStateBus', ...
    'trajectory', 'MargDarshanTrajectoryBus', ...
    'pipeline', 'MargDarshanPipelineBus');
end

function bus = makeBus(value, busName)
%MAKEBUS Recursively map a fixed-size contract struct into bus elements.
% Inputs: value, initialised contract struct; busName, Simulink.Bus name.
% Outputs: bus, nested elements retain contract dimensions and data types.
% Example: b = makeBus(types.egoState(),'MargDarshanEgoStateBus');
names = fieldnames(value);
elements = repmat(Simulink.BusElement, 1, numel(names));
for k = 1:numel(names)
    fieldName = names{k};
    fieldValue = value.(fieldName);
    element = Simulink.BusElement;
    element.Name = fieldName;
    if isstruct(fieldValue)
        nestedName = [busName upperFirst(fieldName)];
        nestedBus = makeBus(fieldValue(1), nestedName);
        assignin('base', nestedName, nestedBus);
        element.DataType = ['Bus: ' nestedName];
        element.Dimensions = size(fieldValue);
    else
        element.DataType = class(fieldValue);
        if islogical(fieldValue)
            element.DataType = 'boolean';
        end
        element.Dimensions = size(fieldValue);
    end
    elements(k) = element;
end
bus = Simulink.Bus;
bus.Elements = elements;
end

function result = upperFirst(value)
%UPPERFIRST Capitalise a field name for a nested bus identifier.
% Inputs: value, field name. Outputs: result, capitalised field name.
% Example: result = upperFirst('agents');
result = [upper(value(1)) value(2:end)];
end
