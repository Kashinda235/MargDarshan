function diagnostics = controlDiagnostics(egoState, selectedTrajectory)
%CONTROLDIAGNOSTICS Compute current trajectory tracking errors.
% Inputs: egoState position (m), yaw (rad), speed (m/s); selectedTrajectory
% world-frame x/y (m), yaw (rad), and v (m/s).
% Outputs: cross-track error (m, positive left), heading error (rad),
% speed error (m/s), and closest trajectory sample index.
% Example: errors = controlDiagnostics(ego,path);
required = {'x','y','yaw','v'};
if ~isstruct(selectedTrajectory) || ~all(isfield(selectedTrajectory,required)) ...
        || isempty(selectedTrajectory.x) || ...
        any([numel(selectedTrajectory.y),numel(selectedTrajectory.yaw), ...
        numel(selectedTrajectory.v)] ~= numel(selectedTrajectory.x)) || ...
        any(~isfinite([selectedTrajectory.x(:);selectedTrajectory.y(:); ...
        selectedTrajectory.yaw(:);selectedTrajectory.v(:)]))
    error('controlDiagnostics:InvalidTrajectory', ...
        'Trajectory must have matching finite x, y, yaw, and v arrays.');
end
if ~all(isfield(egoState,{'x','y','yaw','v'})) || ...
        any(~isfinite([egoState.x egoState.y egoState.yaw egoState.v]))
    error('controlDiagnostics:InvalidEgoState', ...
        'egoState must contain finite x, y, yaw, and v values.');
end
[~,index] = min((selectedTrajectory.x(:)-egoState.x).^2 ...
    +(selectedTrajectory.y(:)-egoState.y).^2);
dx = egoState.x-selectedTrajectory.x(index);
dy = egoState.y-selectedTrajectory.y(index);
crossTrack = -sin(selectedTrajectory.yaw(index))*dx ...
    +cos(selectedTrajectory.yaw(index))*dy;
headingError = atan2(sin(selectedTrajectory.yaw(index)-egoState.yaw), ...
    cos(selectedTrajectory.yaw(index)-egoState.yaw));
diagnostics = struct( ...
    'crossTrackError',crossTrack, ...
    'headingError',headingError, ...
    'speedError',selectedTrajectory.v(index)-egoState.v, ...
    'nearestIndex',index);
end
