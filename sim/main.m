%MAIN One-click comparison of MargDarshan and the lane-following baseline.
% Edit this configuration block before running the full five-scenario batch.

cfg = defaultConfig();
seedCount = 1;
seedStart = 1;
durationS = cfg.simulation.duration;
plannerNames = {'margdarshan','baseline'};
animationScenario = 'village';
animationPlanner = 'margdarshan';
animationFile = 'margdarshan_village.mp4';

options = struct( ...
    'planners', {plannerNames}, ...
    'seedStart', seedStart, ...
    'durationS', durationS, ...
    'measureTiming', true, ...
    'saveResults', true);
results = runBatch( ...
    {'village','intersection','highwayMerge','market','cattleCrossing'}, ...
    seedCount, cfg, options);
disp(results);

animationLog = runSimulation(animationScenario, cfg, seedStart, ...
    struct('planner', animationPlanner, ...
    'durationS', durationS, 'measureTiming', true));
animateRun(animationLog, cfg, struct( ...
    'videoFile', animationFile, 'frameStride', 2));
fprintf('Results saved under results; animation: %s\n', animationFile);
